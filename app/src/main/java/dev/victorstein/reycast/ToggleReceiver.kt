package dev.victorstein.reycast

import android.content.BroadcastReceiver
import android.content.Context
import android.content.Intent
import android.os.SystemClock

class ToggleReceiver : BroadcastReceiver() {
    override fun onReceive(context: Context, intent: Intent) {
        val requestedAtMs = SystemClock.uptimeMillis()
        // shortcut: the receiver is exported without a permission, so any installed app can summon hints (or
        // scroll mode) and turn the user's next keystroke into a click. Accepted on a personal device; if
        // untrusted apps get installed, require a per-install token extra (generated by install.sh, sent by
        // Key Mapper).
        when (intent.action) {
            ACTION_HINTS -> ReyCastOverlay.toggleHints(context.applicationContext, requestedAtMs)
            ACTION_SCROLL -> ReyCastOverlay.toggleScroll(context.applicationContext, requestedAtMs)
            else -> ReyCastOverlay.toggle(context.applicationContext, requestedAtMs)
        }
    }

    companion object {
        const val ACTION_HINTS = "dev.victorstein.reycast.HINTS"
        const val ACTION_SCROLL = "dev.victorstein.reycast.SCROLL"
    }
}
